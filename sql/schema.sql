-- 1. 创建 tasks 数据表（如已存在则跳过）
create table if not exists tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  priority text not null default '中' check (priority in ('高', '中', '低')),
  completed boolean not null default false,
  created_at timestamptz not null default now()
);

-- 2. 开启行级安全（RLS）
alter table tasks enable row level security;

-- 3. 允许匿名（未登录）读取
create policy "Allow anon read" on tasks
  for select using (true);

-- 4. 允许匿名新增
create policy "Allow anon insert" on tasks
  for insert with check (true);

-- 5. 允许匿名修改
create policy "Allow anon update" on tasks
  for update using (true) with check (true);

-- 6. 允许匿名删除
create policy "Allow anon delete" on tasks
  for delete using (true);

-- 说明：
-- - 以上策略为“任何人都能读写”，仅适合课堂教学演示；
-- - 正式项目应改为“登录用户只能操作自己的数据”（接入 Supabase Auth）；
-- - 若提示 policy already exists，说明策略之前已创建过，不影响使用。
